actual object PendingDeepLinkStore {

    private var pendingUri: String? = null

    actual fun store(uri: String) {
        pendingUri = uri
    }

    actual fun consume(): String? {
        val uri = pendingUri
        pendingUri = null
        return uri
    }

    actual fun clear() {
        pendingUri = null
    }
}
